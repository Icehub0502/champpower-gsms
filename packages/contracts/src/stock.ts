export const MoveRef = z
  .object({
    kind: z.literal('document_line'),
    documentId: uuid,
    documentType: z.string(),
    documentNumber: z.string().nullable(),
    lineId: uuid,
    lineName: z.string().nullable(),
    jobId: uuid.nullable(),
    jobNumber: z.string().nullable(),
  })
  .strict();
export type MoveRef = z.infer<typeof MoveRef>;

export const MoveRow = z
  .object({
    id: uuid,
    type: StockMoveType,
    // Signed, as in the ledger: reserve +, unreserve -, issue -, count/adjustment delta.
    qty: z.string(),
    onHandAfter: z.string().nullable(),
    reservedAfter: z.string().nullable(),
    reason: z.string().nullable(),
    at: isoDateTime,
    user: z.object({ id: uuid, name: z.string().nullable() }).strict().nullable(),
    ref: MoveRef.nullable(),
    // Cost roles only; key ABSENT otherwise.
    unitCost: z.string().nullable().optional(),
  })
  .strict();
export type MoveRow = z.infer<typeof MoveRow>;

export const CardQuery = PageQuery.extend({
  // Narrow the history, e.g. to the manual ones.
  type: StockMoveType.optional(),
}).strict();
export type CardQuery = z.infer<typeof CardQuery>;

export const StockCard = z
  .object({
    sku: SkuRow,
    moves: z.object({ items: z.array(MoveRow), total: z.number().int().min(0) }).strict(),
  })
  .strict();
export type StockCard = z.infer<typeof StockCard>;

