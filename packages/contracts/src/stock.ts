export const JobStockLine = z
  .object({
    lineId: uuid,
    parentLineId: uuid.nullable(),
    // What a person reads on the shelf list: the line's name as quoted.
    name: z.string(),
    skuId: uuid,
    skuCode: z.string(),
    skuName: z.string(),
    shelfLocation: z.string().nullable(),
    unit: z.string().nullable(),
    // What must leave the shelf for this line (set children: per-set qty x set qty).
    need: z.string(),
    // Reserved for this line right now (net of what was already pulled).
    reserved: z.string(),
    // Already pulled (this line and, through revisions, the line it was copied from).
    issued: z.string(),
    // The default quantity for the issue button: min(reserved, need - issued).
    toIssue: z.string(),
    // need - issued - reserved, when the SKU is counted and stocked; "0" otherwise. > 0 = รออะไหล่.
    shortfall: z.string(),
    onHand: z.string().nullable(),
    available: z.string().nullable(),
    counted: z.boolean(),
    stockingPolicy: StockingPolicy,
    awaitingParts: z.boolean(),
    // Nothing left to pull for this line.
    done: z.boolean(),
  })
  .strict();
export type JobStockLine = z.infer<typeof JobStockLine>;

export const JobStock = z
  .object({
    jobId: uuid,
    quotation: z.object({ id: uuid, number: z.string().nullable(), revision: z.number().int() }).strict().nullable(),
    lines: z.array(JobStockLine),
    // Part lines of the confirmed quotation that have no SKU: they cannot be pulled or reserved.
    unboundLines: z.array(z.object({ lineId: uuid, name: z.string() }).strict()),
    awaitingParts: z.boolean(),
  })
  .strict();
export type JobStock = z.infer<typeof JobStock>;

export const StockIssueLineInput = z
  .object({
    lineId: uuid,
    qty: StockQtyPositive,
    // Pulling more than this line has reserved (spoiled in fitting, late stock) must be confirmed.
    allowOverReserved: z.boolean().optional(),
  })
  .strict();
export type StockIssueLineInput = z.infer<typeof StockIssueLineInput>;

export const StockIssueInput = z
  .object({
    requestId: RequestId,
    lines: z.array(StockIssueLineInput).min(1).max(100),
  })
  .strict();
export type StockIssueInput = z.infer<typeof StockIssueInput>;

export const StockIssueResult = z
  .object({
    replayed: z.boolean(),
    issued: z.array(
      z
        .object({
          lineId: uuid,
          skuId: uuid,
          skuCode: z.string(),
          qty: z.string(),
          fromReserved: z.string(),
          extra: z.string(),
        })
        .strict(),
    ),
    jobStock: JobStock,
  })
  .strict();
export type StockIssueResult = z.infer<typeof StockIssueResult>;

// What confirm ("ยืนยันผลลูกค้า") tells the screen about stock. Never blocks; it is news.
export const StockConfirmSummary = z
  .object({
    reserved: z.array(z.object({ lineId: uuid, name: z.string(), skuCode: z.string(), qty: z.string() }).strict()),
    // Approved, but the shelf could not cover it: a purchase suggestion was opened, the work order says รออะไหล่.
    shortfalls: z.array(
      z
        .object({
          lineId: uuid, name: z.string(), skuId: uuid, skuCode: z.string(),
          needed: z.string(), reserved: z.string(), short: z.string(),
        })
        .strict(),
    ),
    // The SKU was never counted: nothing reserved, nothing blocked, nothing warned except this note.
    notCounted: z.array(z.object({ lineId: uuid, name: z.string(), skuCode: z.string() }).strict()),
    // Approved part lines with no SKU: cannot reserve.
    unbound: z.array(z.object({ lineId: uuid, name: z.string() }).strict()),
  })
  .strict();
export type StockConfirmSummary = z.infer<typeof StockConfirmSummary>;

export const EMPTY_STOCK_CONFIRM_SUMMARY: StockConfirmSummary = { reserved: [], shortfalls: [], notCounted: [], unbound: [] };

