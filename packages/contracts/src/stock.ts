export type CountSheetPage = z.infer<typeof CountSheetPage>;

// Absolute quantity ("I counted 12"). Any number of times; 0 is a real answer.
export const CountInput = z
  .object({
    requestId: RequestId,
    qty: StockQtyInput,
    // Free text, required. The screen may pre-fill "ตั้งยอดตั้งต้น".
    reason: z.string(),
  })
  .strict();
export type CountInput = z.infer<typeof CountInput>;

// Absolute new quantity of a SKU that is already counted.
export const AdjustInput = z
  .object({
    requestId: RequestId,
    newQty: StockQtyInput,
    reason: z.string(),
  })
  .strict();
export type AdjustInput = z.infer<typeof AdjustInput>;

export const StockChangeResult = z
  .object({
    moveId: uuid,
    // true = this requestId was already applied; nothing was written this time.
    replayed: z.boolean(),
    sku: SkuRow,
    beforeOnHand: z.string().nullable(),
    afterOnHand: z.string(),
    deltaQty: z.string(),
    // The count found less than is reserved: available is now negative. Informational.
    belowReserved: z.boolean(),
  })
  .strict();
export type StockChangeResult = z.infer<typeof StockChangeResult>;

