// Stock (WO-006): SKUs, counts, adjustments, the stock card, the per-job issue
// list, low stock, the catalog <-> SKU link, and the owner's daily/integrity views.
//
//   GET    /api/stock/skus                      SkuListQuery        -> SkuPage            (search, filter, paginated)
//   GET    /api/stock/skus/by-code/:code                            -> SkuRow             (QR scan: skus.code is the QR value)
//   GET    /api/stock/skus/:id                                      -> SkuDetail
//   POST   /api/stock/skus                      SkuCreateInput      -> SkuRow             (no balance row is created)
//   PATCH  /api/stock/skus/:id                  SkuPatchInput       -> SkuRow
//   GET    /api/stock/count-sheet               CountSheetQuery     -> CountSheetPage     (had-stock parts first)
//   POST   /api/stock/skus/:id/count            CountInput          -> StockChangeResult  (ตั้งยอด: absolute qty)
//   POST   /api/stock/skus/:id/adjust           AdjustInput         -> StockChangeResult  (ปรับยอด: absolute qty + reason)
//   GET    /api/stock/low                       LowStockQuery       -> SkuPage            (counted, stocked, available <= reorder point)
//   GET    /api/stock/skus/:id/card             CardQuery           -> StockCard          (balance + full move history)
//   GET    /api/jobs/:jobId/stock                                   -> JobStock           (what to pull, what is reserved/short)
//   POST   /api/jobs/:jobId/stock/issue         StockIssueInput          -> StockIssueResult        (เบิก: issue + unreserve together)
//   GET    /api/stock/unbound-lines             UnboundLinesQuery   -> UnboundLinePage    (live part lines with no SKU)
//   GET    /api/stock/catalog-links             CatalogLinksQuery   -> CatalogLinkPage
//   PUT    /api/stock/catalog-items/:itemId/sku CatalogBindInput    -> CatalogLinkRow     (bind)
//   DELETE /api/stock/catalog-items/:itemId/sku                     -> CatalogLinkRow     (unbind)
//   POST   /api/stock/catalog-items/:itemId/sku/create CatalogCreateSkuInput -> CatalogLinkRow (new SKU from the item, bound)
//   GET    /api/stock/adjustments               AdjustmentsQuery    -> DailyAdjustments   (owner / manager)
//   GET    /api/stock/integrity                                     -> IntegrityReport    (owner / manager)
//
// Realtime: after any stock write the server emits `stock:changed` to the shop's staff room with
// StockChangedEvent. It is a REFETCH SIGNAL (ids only), never a row.
//
// COST NEVER REACHES A ROLE THAT MAY NOT SEE IT (CLAUDE.md s12.2). `avgCost`, `stockValue` and a
// move's `unitCost` are OPTIONAL keys: the server leaves the key out entirely for advisor,
// technician and viewer - it does not send null and does not rely on the screen to hide it. Every
// object is .strict(), so a cost field cannot be added server-side without a change to this file.
//
// Quantities are decimal strings ("12", "1.5"), never floats. A SKU with no balance row is NOT
// COUNTED: counted=false and onHand/reserved/available are null (not "0") - the screen must show
// "ยังไม่ตั้งยอด", never "หมด".

import { z } from 'zod';
import { PageQuery, uuid } from './common.js';
import { InvalidRequestError } from './errors.js';

const isoDateTime = z.string().datetime();

/** numeric(12,2) as text, >= 0, at most 2 decimals. A request quantity (zero allowed). */
export const StockQtyInput = z
  .string()
  .trim()
  .regex(/^\d{1,10}(\.\d{1,2})?$/, 'invalid_qty');
/** A request quantity that must be > 0. */
export const StockQtyPositive = StockQtyInput.refine((v) => Number(v) > 0, 'invalid_qty');

/** Generated by the screen once per dialog/button press and resent unchanged on a retry. */
export const RequestId = uuid;

export const StockingPolicy = z.enum(['stocked', 'buy_to_order']);
export type StockingPolicy = z.infer<typeof StockingPolicy>;

export const StockStatus = z.enum(['not_counted', 'out', 'low', 'ok']);
export type StockStatus = z.infer<typeof StockStatus>;

export const StockMoveType = z.enum([
  'receipt', 'reserve', 'unreserve', 'issue', 'return', 'adjustment', 'count', 'transfer_out', 'transfer_in',
]);
export type StockMoveType = z.infer<typeof StockMoveType>;

// -----------------------------------------------------------------------------
// SKU
// -----------------------------------------------------------------------------

export const SkuRow = z
  .object({
    id: uuid,
    // The text a QR label carries.
    code: z.string(),
    name: z.string(),
    category: z.string().nullable(),
    unit: z.string(),
    stockingPolicy: StockingPolicy,
    reorderPoint: z.string().nullable(),
    shelfLocation: z.string().nullable(),
    isActive: z.boolean(),
    // Prototype showed qty > 0 for this part. Only a sort hint for the count screen; null = not from the prototype.
    legacyHadStock: z.boolean().nullable(),
    counted: z.boolean(),
    status: StockStatus,
    onHand: z.string().nullable(),
    reserved: z.string().nullable(),
    // on_hand - reserved. May be negative when a count found less than is reserved.
    available: z.string().nullable(),
    // Cost roles only (owner / manager / assistant_manager / accountant). Key ABSENT for everyone else.
    avgCost: z.string().nullable().optional(),
    stockValue: z.string().nullable().optional(),
  })
  .strict();
export type SkuRow = z.infer<typeof SkuRow>;

export const SkuPage = z.object({ items: z.array(SkuRow), total: z.number().int().min(0) }).strict();
export type SkuPage = z.infer<typeof SkuPage>;

export const SkuDetail = SkuRow.extend({
  catalogItems: z.array(z.object({ id: uuid, category: z.string(), name: z.string() }).strict()),
}).strict();
export type SkuDetail = z.infer<typeof SkuDetail>;

export const SkuListQuery = PageQuery.extend({
  q: z.string().trim().max(80).optional(),
  category: z.string().trim().max(80).optional(),
  status: z.enum(['all', 'not_counted', 'counted', 'out', 'low']).default('all'),
  active: z.enum(['active', 'inactive', 'all']).default('active'),
}).strict();
export type SkuListQuery = z.infer<typeof SkuListQuery>;

const SkuText = z.string().trim().min(1).max(200);

export const SkuCreateInput = z
  .object({
    code: z.string().trim().min(1).max(100),
    name: SkuText,
    category: z.string().trim().min(1).max(100).optional(),
    unit: z.string().trim().min(1).max(30).optional(),
    stockingPolicy: StockingPolicy.optional(),
    reorderPoint: StockQtyInput.optional(),
    shelfLocation: z.string().trim().min(1).max(100).optional(),
  })
  .strict();
export type SkuCreateInput = z.infer<typeof SkuCreateInput>;

// code is not editable: it is printed on shelf labels and referenced by QR. null clears an optional text.
export const SkuPatchInput = z
  .object({
    name: SkuText.optional(),
    category: z.string().trim().min(1).max(100).nullable().optional(),
    unit: z.string().trim().min(1).max(30).optional(),
    stockingPolicy: StockingPolicy.optional(),
    reorderPoint: StockQtyInput.nullable().optional(),
    shelfLocation: z.string().trim().min(1).max(100).nullable().optional(),
    isActive: z.boolean().optional(),
  })
  .strict()
  .refine((v) => Object.keys(v).length > 0, { message: 'empty_patch' });
export type SkuPatchInput = z.infer<typeof SkuPatchInput>;

